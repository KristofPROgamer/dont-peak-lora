"""
=========================================================================================
SDXL TEXT ENCODER LORA MERGER & FORMATTER
=========================================================================================
BACKGROUND:
Stable Diffusion XL (SDXL) is unique because it uses TWO text encoders to understand 
prompts:
  1. TE1: CLIP ViT-L (The same architecture used in SD 1.5)
  2. TE2: CLIP ViT-bigG (A much larger, more complex text encoder)

When you train a custom text encoder LoRA (like a cipher/encryption concept) using standard
Hugging Face (HF) PEFT libraries, the output is saved in a raw, academic format. 
However, popular UI tools like ComfyUI and the HF Diffusers library require specific, 
completely different dictionary structures to actually load those weights.

WHAT THIS SCRIPT DOES:
1. Takes two independently trained PEFT LoRA folders (one for TE1, one for TE2).
2. Validates their configuration files to ensure they are healthy.
3. Translates their internal tensor names (keys) into the format ComfyUI expects.
4. Translates their internal tensor names into the format HF Diffusers expects.
5. Merges them together and spits out two ready-to-use .safetensors files.
=========================================================================================
"""

import os
import json
import torch
from safetensors.torch import load_file, save_file

# =======================================================================================
# PHASE 1: CONFIGURATION VALIDATION
# =======================================================================================
def validate_adapter_config(config_path, name):
    """
    Reads the 'adapter_config.json' generated by Hugging Face PEFT.
    
    WHY THIS MATTERS:
    ComfyUI cannot automatically guess how "strong" a LoRA was intended to be. It needs 
    a mathematical variable called 'Alpha' to calculate the intended strength of the weights 
    (Strength = Alpha / Rank). If we don't extract the exact Alpha the model was trained 
    with here, the UI might apply the LoRA at 10x strength, resulting in pure noise.
    """
    print(f"\n[VALIDATING CONFIG] {name}")
    if not os.path.exists(config_path):
        raise FileNotFoundError(f"CRITICAL: Cannot find config at {config_path}")
        
    with open(config_path, "r") as f:
        config = json.load(f)
        
    peft_type = config.get("peft_type", "UNKNOWN")
    rank = config.get("r", "UNKNOWN")
    alpha = config.get("lora_alpha", "UNKNOWN")
    
    print(f"  > PEFT Type : {peft_type}")
    print(f"  > Rank (r)  : {rank}")
    print(f"  > Alpha     : {alpha}")
    
    if peft_type != "LORA":
        print(f"  ! WARNING: Expected PEFT type 'LORA', got '{peft_type}'")
    if rank == "UNKNOWN" or alpha == "UNKNOWN":
        print("  ! WARNING: Rank or Alpha not found. Is this a valid PEFT config?")

    return rank, alpha

# =======================================================================================
# PHASE 2: COMFYUI FORMAT TRANSLATION
# =======================================================================================
def convert_to_comfy(peft_state_dict, prefix, actual_alpha):
    """
    Translates raw Hugging Face PEFT keys into flattened ComfyUI keys.
    
    COMFYUI'S RULES:
    1. It hates nested structures (dots). It wants underscores.
    2. It needs to know if the weight belongs to TE1 (lora_te1_) or TE2 (lora_te2_).
    3. It refers to the two matrices of a LoRA as 'lora_down' and 'lora_up' (HF calls 
       them 'lora_A' and 'lora_B').
    4. It requires a dummy '.alpha' tensor attached to every single layer to do its math.
    """
    comfy_dict = {}
    for key, tensor in peft_state_dict.items():
        
        # STEP 1: Strip the generic Hugging Face wrapper text.
        # HF wraps everything in "base_model.model.". ComfyUI doesn't want this.
        clean_key = key.replace("base_model.model.", "")
        
        # STEP 2: The "Missing Prefix" Bug Fix.
        # Sometimes, HF PEFT drops the "text_model." prefix during training if you target 
        # the encoder directly. ComfyUI strictly requires "text_model.encoder" to exist. 
        # If it's missing, we inject it back in to prevent ComfyUI from rejecting the key.
        if not clean_key.startswith("text_model.") and clean_key.startswith("encoder."):
            clean_key = "text_model." + clean_key
            
        # STEP 3: Translate 'lora_A' to 'lora_down' and inject the Alpha.
        if "lora_A" in clean_key:
            # Remove the old suffix
            base_name = clean_key.replace(".lora_A.weight", "")
            
            # Create the Comfy key: prefix + swap dots for underscores + add down.weight
            comfy_key = prefix + base_name.replace(".", "_") + ".lora_down.weight"
            comfy_dict[comfy_key] = tensor
            
            # INJECT ALPHA: We create a 1-dimensional tensor containing the actual_alpha 
            # value we pulled from the JSON config. This prevents the "deep-fried image" bug.
            alpha_key = prefix + base_name.replace(".", "_") + ".alpha"
            comfy_dict[alpha_key] = torch.tensor(float(actual_alpha), dtype=tensor.dtype)
            
        # STEP 4: Translate 'lora_B' to 'lora_up'. (No alpha injection needed here).
        elif "lora_B" in clean_key:
            base_name = clean_key.replace(".lora_B.weight", "")
            comfy_key = prefix + base_name.replace(".", "_") + ".lora_up.weight"
            comfy_dict[comfy_key] = tensor
            
    return comfy_dict

# =======================================================================================
# PHASE 3: HUGGING FACE DIFFUSERS TRANSLATION
# =======================================================================================
def convert_to_hf_sdxl(peft_state_dict, prefix):
    """
    Translates raw Hugging Face PEFT keys into the HF Diffusers format.
    
    DIFFUSERS' RULES:
    Unlike ComfyUI, Diffusers likes the original dots and `lora_A`/`lora_B` naming. 
    However, because SDXL has two text encoders, it needs a namespace prefix so it knows 
    where to send the weights.
    - TE1 gets the prefix "text_encoder."
    - TE2 gets the prefix "text_encoder_2."
    """
    hf_dict = {}
    for key, tensor in peft_state_dict.items():
        # Simply append the correct namespace to the very front of the key.
        hf_dict[prefix + key] = tensor
    return hf_dict

# =======================================================================================
# PHASE 4: MAIN EXECUTION (THE ENGINE)
# =======================================================================================
if __name__ == "__main__":
    
    # ---> USER CONFIGURATION <---
    # Point these to the folders containing your adapter_model.safetensors and adapter_config.json
    DIR_TE1 = "C:\\Users\\YOUR_USER\\Desktop\\Dont_Peak_Company_LoRA\\sd1.5\\checkpoints_phase2\\lora_epoch8_cos0.8455"
    DIR_TE2 = "C:\\Users\\YOUR_USER\\Desktop\\Dont_Peak_Company_LoRA\\sdxl\\Final_phase2"

    print("Starting SDXL Text Encoder LoRA Merger Pipeline...")

    # 1. Validate Configurations and grab the Alphas
    rank_te1, alpha_te1 = validate_adapter_config(os.path.join(DIR_TE1, "adapter_config.json"), "TE1 (ViT-L)")
    rank_te2, alpha_te2 = validate_adapter_config(os.path.join(DIR_TE2, "adapter_config.json"), "TE2 (ViT-bigG)")

    # It's okay if TE1 and TE2 have different ranks (e.g., TE1 is smaller, so it might use 
    # Rank 32, while TE2 uses Rank 64), but we print a notice just so the user is aware.
    if rank_te1 != rank_te2:
        print(f"\n[!] NOTICE: TE1 Rank ({rank_te1}) and TE2 Rank ({rank_te2}) differ. This is mathematically allowed.")

    # 2. Load the raw weights into memory
    print("\n[LOADING WEIGHTS]")
    te1_state = load_file(os.path.join(DIR_TE1, "adapter_model.safetensors"))
    te2_state = load_file(os.path.join(DIR_TE2, "adapter_model.safetensors"))
    print(f"  > TE1 loaded: {len(te1_state)} tensors.")
    print(f"  > TE2 loaded: {len(te2_state)} tensors.")

    # 3. Process and Save the ComfyUI Format
    print("\n[PROCESSING COMFYUI FORMAT]")
    comfy_lora = {}
    
    # We pass the extracted Alphas into the function here so it builds the math correctly.
    te1_comfy = convert_to_comfy(te1_state, "lora_te1_", alpha_te1)
    te2_comfy = convert_to_comfy(te2_state, "lora_te2_", alpha_te2)
    
    comfy_lora.update(te1_comfy)
    comfy_lora.update(te2_comfy)

    comfy_filename = "sdxl_cipher_comfyui.safetensors"
    save_file(comfy_lora, comfy_filename)
    print(f"  > Saved: {comfy_filename} ({len(comfy_lora)} keys)")

    # 4. Process and Save the Hugging Face Diffusers Format
    print("\n[PROCESSING HUGGING FACE FORMAT]")
    hf_lora = {}
    
    te1_hf = convert_to_hf_sdxl(te1_state, "text_encoder.")
    te2_hf = convert_to_hf_sdxl(te2_state, "text_encoder_2.")
    
    hf_lora.update(te1_hf)
    hf_lora.update(te2_hf)

    hf_filename = "sdxl_cipher_hf_diffusers.safetensors"
    save_file(hf_lora, hf_filename)
    print(f"  > Saved: {hf_filename} ({len(hf_lora)} keys)")

    print("\n[SUCCESS] Pipeline Complete! Both formats have been generated in your current working directory.")